import { writeFileSync } from 'node:fs'
import { LearningRanker, learningKey, type RewardTable } from '../src/domain/sim/learningRanker.ts'
import { rng } from '../src/domain/util/rng.ts'
import type { CandidateRanker } from '../src/domain/sim/ranker.ts'
import { runStrategy } from './compare.ts'

const table: RewardTable = {}
const random = rng(813)
const policy = new LearningRanker(table)
const training: CandidateRanker = {
  id: 'rl.training',
  mode: 'rl',
  async rank(input) {
    const result = await policy.rank(input)
    const explore = new Map(input.candidates.map((candidate) => [candidate.id, random.next()]))
    if (random.next() >= 0.6) return result
    const feasible = input.candidates.filter((candidate) => candidate.feasible && !candidate.keepsAssignment)
    const explored = feasible.sort((a, b) => explore.get(a.id)! - explore.get(b.id)!).map((candidate) => candidate.id)
    return { ...result, order: [...explored, ...result.order.filter((id) => !explored.includes(id))] }
  },
}
const disasters = ['flood', 'fire', 'earthquake'] as const
const options = { strategy: 'rules', step: 5, max: 3600 } as const

for (const disaster of disasters) {
  for (let seed = 1; seed <= 60; seed++) {
    await runStrategy({
      ...options, seed, disaster, ranker: training,
      onReward(candidate, now, reward) {
        const key = learningKey({ disaster, now }, candidate)
        const estimate = table[key] ??= { value: 0, trials: 0 }
        estimate.value += (reward - estimate.value) / ++estimate.trials
      },
    })
  }
}

for (const disaster of disasters) {
  let rules = 0
  let learned = 0
  let covered = 0
  let changed = 0
  for (let seed = 101; seed <= 112; seed++) {
    const baseline = await runStrategy({ ...options, seed, disaster })
    const experiment = await runStrategy({ ...options, seed, disaster, ranker: policy })
    rules += baseline.metrics.onTime
    learned += experiment.metrics.onTime
    covered += experiment.planSets.filter((set) => set.rankingMode === 'rl').length
    const original = new Map(baseline.planSets.map((set) => [set.id, set.confirmed?.title]))
    changed += experiment.planSets.filter((set) => set.confirmed && original.has(set.id) && original.get(set.id) !== set.confirmed.title).length
  }
  console.log(`${disaster}: on-time rule=${rules} learned=${learned}, learned sets=${covered}, changed confirmations=${changed}`)
}

const entries = Object.entries(table).sort(([a], [b]) => a.localeCompare(b)).map(([key, entry]) => (
  `  ${JSON.stringify(key)}: { value: ${entry.value.toFixed(6)}, trials: ${entry.trials} },`
))
writeFileSync('src/domain/sim/dispatchRewards.ts', [
  '// Generated by npm run rl:train. Training seeds: 1–60 per disaster.',
  "import type { RewardTable } from './learningRanker.ts'",
  '',
  'export const DISPATCH_REWARDS: RewardTable = {', ...entries, '}', '',
].join('\n'))
console.log(`Training observations: ${Object.values(table).reduce((sum, entry) => sum + entry.trials, 0)} in ${entries.length} table cells`)
